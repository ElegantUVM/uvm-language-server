"""Generate uvmls/shim/uvm_macros.svh from a UVM source tree.

The shim lets the indexer parse UVM code correctly when the real UVM library is
not configured. Without it, slang drops unknown macros such as `uvm_fatal and the
statement after `if (...) `uvm_fatal(...)` becomes the body of the `if`.

Each macro keeps its real name and arity but gets a light body:
  * `uvm_info / `uvm_warning / `uvm_error / `uvm_fatal (and _context) ->
    `begin if (0) $display(ID, MSG); end`, so calls written in the message are parsed
  * other reporting / sequence / callback / pack / record macros -> `begin end`
  * *_utils / *_registry macros -> `typedef uvm_*_registry #(T) type_id;`
    so the indexer can see factory registration the same way it does with real UVM
  * `uvm_declare_p_sequencer(S) -> `S p_sequencer;`
  * `uvm_new_func -> the component constructor it declares, so the class has one
  * everything else -> empty

Usage: python tools/gen_uvm_shim.py <UVM_HOME>/src > uvmls/shim/uvm_macros.svh
"""

import os
import re
import sys

DEFINE_RE = re.compile(r"^\s*`define\s+([A-Za-z_]\w*)")


def read_defines(src_dir):
    """Yield (name, params or None, value) for every `define in the tree."""
    for dirpath, _, files in os.walk(src_dir):
        for fn in sorted(files):
            if not fn.endswith((".sv", ".svh")):
                continue
            with open(os.path.join(dirpath, fn), encoding="utf-8", errors="replace") as f:
                lines = f.read().split("\n")
            for i, line in enumerate(lines):
                m = DEFINE_RE.match(line)
                if not m:
                    continue
                name = m.group(1)
                rest = line[m.end():]
                # Join continuation lines so parameter lists spanning lines parse.
                j = i
                while rest.endswith("\\") and j + 1 < len(lines):
                    j += 1
                    rest = rest[:-1] + " " + lines[j]
                params = None
                if rest.startswith("("):
                    depth, k = 0, 0
                    for k, ch in enumerate(rest):
                        depth += ch == "("
                        depth -= ch == ")"
                        if depth == 0:
                            break
                    params = rest[1:k]
                    rest = rest[k + 1:]
                yield name, params, rest.strip()


STATEMENT_PREFIXES = (
    "uvm_info", "uvm_warning", "uvm_error", "uvm_fatal", "uvm_message_add",
    "uvm_do", "uvm_create", "uvm_send", "uvm_rand_send",
    "uvm_pack", "uvm_unpack", "uvm_record", "uvm_print", "uvm_compare",
    "uvm_copier", "uvm_rand_send",
)


def body_for(name, params):
    if name == "uvm_declare_p_sequencer":
        return f"{params.split(',')[0].strip()} p_sequencer;"
    if name == "uvm_new_func":
        return "function new (string name, uvm_component parent); super.new(name, parent); endfunction"
    if name in ("uvm_file",):
        return "`__FILE__"
    if name in ("uvm_line",):
        return "`__LINE__"
    if re.match(r"uvm_(component|object)(_abstract)?(_param)?_utils(_begin)?$", name) or \
       re.match(r"uvm_(component|object)(_abstract)?_registry$", name):
        kind = "component" if "component" in name else "object"
        reg = f"uvm_abstract_{kind}_registry" if "abstract" in name else f"uvm_{kind}_registry"
        first = params.split(",")[0].strip() if params else "int"
        return f"typedef {reg} #({first}) type_id;"
    if name.endswith("_utils_end") or name.startswith("uvm_field_"):
        return ""
    if re.match(r"uvm_(info|warning|error|fatal|message)(_context)?_begin$", name):
        return "begin"
    if re.match(r"uvm_(info|warning|error|fatal|message)(_context)?_end$", name):
        return "end"
    if re.match(r"uvm_(info|warning|error|fatal)(_context)?$", name):
        return "begin if (0) $display(ID, MSG); end"
    if name.startswith(("uvm_do_callbacks", "uvm_do_obj_callbacks")):
        return "begin end"
    if name.startswith(STATEMENT_PREFIXES):
        return "begin end"
    return ""


def main(src_dir):
    seen = {}
    for name, params, value in read_defines(src_dir):
        if name.startswith(("m_", "M_", "M__", "_")) or name in seen:
            continue
        if params is None:
            # Keep simple numeric / string valued UVM_* constants (UVM_REG_DATA_WIDTH etc.).
            if name.startswith("UVM_") and re.fullmatch(r"\d+|\"[^\"]*\"", value):
                seen[name] = f"`define {name} {value}"
            elif name.startswith("uvm_"):
                seen[name] = f"`define {name} {body_for(name, '')}".rstrip()
            continue
        if not name.startswith("uvm_"):
            continue
        seen[name] = f"`define {name}({params}) {body_for(name, params)}".rstrip()

    out = [
        "// Generated by tools/gen_uvm_shim.py - do not edit.",
        "// Lightweight stand-ins for the UVM macros, used by the UVM language server",
        "// when the real UVM library is not configured. Names and arity match UVM;",
        "// bodies are reduced to what the indexer needs to parse code correctly.",
        "`ifndef UVM_MACROS_SVH",
        "`define UVM_MACROS_SVH",
        "",
    ]
    out += [seen[k] for k in sorted(seen)]
    out += ["", "`endif", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
